/* Related products: prefer same categories (any overlap), excluding current.
   Fills remaining slots from other products. */
window.getRelatedProducts = function (id, n) {
  n = n || 4;
  const p = window.PRODUCTS[id];
  if (!p) return [];
  const cats = (p.category || '').split(/\s+/);
  const hasOverlap = (other) => {
    const oc = (window.PRODUCTS[other].category || '').split(/\s+/);
    return oc.some(c => cats.includes(c));
  };
  const sameCat = window.PRODUCT_ORDER.filter(k => k !== id && hasOverlap(k));
  if (sameCat.length >= n) return sameCat.slice(0, n);
  const others = window.PRODUCT_ORDER.filter(k => k !== id && !hasOverlap(k));
  return sameCat.concat(others).slice(0, n);
};

/* localStorage-backed cart, shared across shop + product pages */
window.bpsCart = {
  get() {
    try { return JSON.parse(localStorage.getItem('bpsCart') || '[]'); }
    catch (e) { return []; }
  },
  set(c) { localStorage.setItem('bpsCart', JSON.stringify(c)); },
  count() { return this.get().reduce((s, it) => s + it.qty, 0); },
  add(item) {
    const c = this.get();
    c.push(item);
    this.set(c);
  }
};

window.renderNavCartCount = function () {
  const el = document.getElementById('navCartCount');
  if (!el) return;
  const n = window.bpsCart.count();
  el.textContent = '(' + n + ')';
  const btn = document.getElementById('navCartBtn');
  if (btn) btn.classList.toggle('active', n > 0);
};
